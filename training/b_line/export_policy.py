"""Export the trained PPO actor to firmware/sr_support_b_ptk/include/policy_b.h.

The exported network is the deterministic policy mean:
    h1 = tanh(W1 @ obs + b1)
    h2 = tanh(W2 @ h1 + b2)
    act = clip(W3 @ h2 + b3, -1, 1)

Example (from the repository root):
  python -m training.b_line.export_policy --robot ptk7452 --verify
"""

from __future__ import annotations

import argparse
import subprocess
import tempfile
from pathlib import Path

import numpy as np
import torch
from stable_baselines3 import PPO

from .selfright_env import ROBOT_SPECS

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[1]
DEFAULT_OUT = REPO / "firmware" / "sr_support_b_ptk" / "include" / "policy_b.h"


def _fmt_2d(a: np.ndarray) -> str:
    return ",\n".join(
        "{" + ", ".join(f"{v:.9e}f" for v in row) + "}" for row in a
    )


def _fmt_1d(a: np.ndarray) -> str:
    return "{" + ", ".join(f"{v:.9e}f" for v in a) + "}"


def extract_weights(model: PPO):
    if model.get_vec_normalize_env() is not None:
        raise SystemExit("VecNormalize is not supported: the firmware has no observation normalizer.")

    policy = model.policy
    pi = policy.mlp_extractor.policy_net
    linears = [m for m in pi if isinstance(m, torch.nn.Linear)]
    acts = [m for m in pi if isinstance(m, (torch.nn.Tanh, torch.nn.ReLU))]
    if len(linears) != 2 or len(acts) != 2 or not all(isinstance(a, torch.nn.Tanh) for a in acts):
        raise SystemExit(f"Unexpected policy architecture: {pi}")

    w1 = linears[0].weight.detach().numpy().astype(np.float32)
    b1 = linears[0].bias.detach().numpy().astype(np.float32)
    w2 = linears[1].weight.detach().numpy().astype(np.float32)
    b2 = linears[1].bias.detach().numpy().astype(np.float32)
    w3 = policy.action_net.weight.detach().numpy().astype(np.float32)
    b3 = policy.action_net.bias.detach().numpy().astype(np.float32)

    hidden = w1.shape[0]
    assert w1.shape[1] == policy.observation_space.shape[0]
    assert w2.shape == (hidden, hidden)
    assert w3.shape == (policy.action_space.shape[0], hidden)
    return w1, b1, w2, b2, w3, b3


def forward_numpy(obs: np.ndarray, weights) -> np.ndarray:
    w1, b1, w2, b2, w3, b3 = weights
    h1 = np.tanh(obs @ w1.T + b1)
    h2 = np.tanh(h1 @ w2.T + b2)
    return np.clip(h2 @ w3.T + b3, -1.0, 1.0)


def write_header(out: Path, weights, model_path: str) -> None:
    w1, b1, w2, b2, w3, b3 = weights
    obs_dim, hidden, act_dim = w1.shape[1], w1.shape[0], w3.shape[0]
    text = f"""#pragma once
// Auto-generated by sim/export_policy.py from {model_path}
// Do not edit by hand.

#include <math.h>

#define POLICY_OBS_DIM {obs_dim}
#define POLICY_ACT_DIM {act_dim}
#define POLICY_HIDDEN {hidden}

static const float POLICY_W1[POLICY_HIDDEN][POLICY_OBS_DIM] = {{
{_fmt_2d(w1)}
}};
static const float POLICY_B1[POLICY_HIDDEN] = {_fmt_1d(b1)};

static const float POLICY_W2[POLICY_HIDDEN][POLICY_HIDDEN] = {{
{_fmt_2d(w2)}
}};
static const float POLICY_B2[POLICY_HIDDEN] = {_fmt_1d(b2)};

static const float POLICY_W3[POLICY_ACT_DIM][POLICY_HIDDEN] = {{
{_fmt_2d(w3)}
}};
static const float POLICY_B3[POLICY_ACT_DIM] = {_fmt_1d(b3)};

static inline void policy_forward(const float *obs, float *act) {{
    static float h1[POLICY_HIDDEN];
    static float h2[POLICY_HIDDEN];
    for (int j = 0; j < POLICY_HIDDEN; ++j) {{
        float s = POLICY_B1[j];
        for (int i = 0; i < POLICY_OBS_DIM; ++i) s += POLICY_W1[j][i] * obs[i];
        h1[j] = tanhf(s);
    }}
    for (int j = 0; j < POLICY_HIDDEN; ++j) {{
        float s = POLICY_B2[j];
        for (int i = 0; i < POLICY_HIDDEN; ++i) s += POLICY_W2[j][i] * h1[i];
        h2[j] = tanhf(s);
    }}
    for (int j = 0; j < POLICY_ACT_DIM; ++j) {{
        float s = POLICY_B3[j];
        for (int i = 0; i < POLICY_HIDDEN; ++i) s += POLICY_W3[j][i] * h2[i];
        act[j] = fminf(1.0f, fmaxf(-1.0f, s));
    }}
}}
"""
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)


def verify_with_c(header: Path, weights, n: int = 512, seed: int = 0) -> float:
    src = ROOT / "policy_stdin.c"
    with tempfile.TemporaryDirectory() as td:
        exe = Path(td) / "policy_stdin"
        subprocess.run(
            [
                "clang",
                "-O2",
                f"-I{header.parent}",
                f'-DPOLICY_INCLUDE="{header.name}"',
                str(src),
                "-lm",
                "-o",
                str(exe),
            ],
            check=True,
        )
        rng = np.random.default_rng(seed)
        obs = rng.normal(0.0, 1.0, size=(n, weights[0].shape[1])).astype(np.float32)
        proc = subprocess.run(
            [str(exe)], input=obs.tobytes(), stdout=subprocess.PIPE, check=True
        )
        acts_c = np.frombuffer(proc.stdout, dtype=np.float32).reshape(n, weights[4].shape[0])
    acts_py = forward_numpy(obs, weights)
    return float(np.max(np.abs(acts_c - acts_py)))


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--robot", choices=sorted(ROBOT_SPECS), default="selfrising_sr5")
    p.add_argument("--model", type=str, default=None)
    p.add_argument("--out", type=str, default=None)
    p.add_argument("--verify", action="store_true", help="compile the C header and compare outputs")
    args = p.parse_args()

    model_path = args.model or str(ROOT / "models" / f"ppo_{args.robot}" / "final.zip")
    out = Path(args.out) if args.out else DEFAULT_OUT

    model = PPO.load(model_path, device="cpu")
    weights = extract_weights(model)
    write_header(out, weights, model_path)
    print(f"wrote {out} ({out.stat().st_size} bytes) for {args.robot}")

    rng = np.random.default_rng(1)
    obs = rng.normal(0.0, 1.0, size=(16, weights[0].shape[1])).astype(np.float32)
    py = forward_numpy(obs, weights)
    sb3 = np.clip(np.array([model.predict(o, deterministic=True)[0] for o in obs]), -1, 1)
    print(f"max |numpy - sb3.predict| = {np.max(np.abs(py - sb3)):.3e}")

    if args.verify:
        diff = verify_with_c(out, weights)
        print(f"max |C - numpy| = {diff:.3e}")
        if diff > 1e-5:
            raise SystemExit("C export mismatch")
        print("C export verified")


if __name__ == "__main__":
    main()
