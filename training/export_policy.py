#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Export a trained SB3 PPO policy to firmware/sr_support_2dof/policy_network.h.

Requirements:
  - net_arch=[64, 64], activation_fn=Tanh, squash_output=True
  - observation layout must match env_sr_2dof.py (6 values)
  - action layout must be 2

Example:
    python training/export_policy.py --model models/sr_ppo.zip
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import torch
from stable_baselines3 import PPO

DEFAULT_OUT = (
    Path(__file__).resolve().parent.parent
    / "firmware"
    / "sr_support_2dof"
    / "policy_network.h"
)


def fmt_array(name: str, array) -> str:
    flat = np.asarray(array, dtype=np.float64).reshape(-1)
    lines = [f"static const float {name}[{flat.size}] = {{"]
    for i in range(0, flat.size, 8):
        chunk = ", ".join(f"{v:.9g}f" for v in flat[i : i + 8])
        lines.append("  " + chunk + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Export PPO policy to C header")
    parser.add_argument("--model", required=True, help="path to .zip model")
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    args = parser.parse_args()

    model = PPO.load(args.model, device="cpu")
    policy = model.policy

    if not getattr(policy, "squash_output", False):
        raise SystemExit(
            "Policy was not trained with squash_output=True; retrain with "
            "training/train_ppo.py or export would not match deployment."
        )

    mlp = policy.mlp_extractor.policy_net
    linears = [m for m in mlp if isinstance(m, torch.nn.Linear)]
    if len(linears) != 2:
        raise SystemExit(f"Expected 2 hidden Linear layers, found {len(linears)}")

    h1, h2 = linears
    action_layer = policy.action_net
    if not isinstance(action_layer, torch.nn.Linear):
        raise SystemExit("action_net is not a Linear layer")

    obs_dim = int(policy.observation_space.shape[0])
    act_dim = int(policy.action_space.shape[0])
    hidden = int(h1.out_features)

    if h1.in_features != obs_dim:
        raise SystemExit("First layer input does not match observation dim")
    if h2.in_features != hidden or h2.out_features != hidden:
        raise SystemExit("Hidden layers do not match [hidden, hidden]")
    if h1.out_features != hidden:
        raise SystemExit("Unexpected first hidden size")
    if action_layer.in_features != hidden or action_layer.out_features != act_dim:
        raise SystemExit("Action layer shape mismatch")

    w1 = h1.weight.detach().cpu().numpy()
    b1 = h1.bias.detach().cpu().numpy()
    w2 = h2.weight.detach().cpu().numpy()
    b2 = h2.bias.detach().cpu().numpy()
    w3 = action_layer.weight.detach().cpu().numpy()
    b3 = action_layer.bias.detach().cpu().numpy()

    header = f"""// Auto-generated by training/export_policy.py
// Model: {Path(args.model).name}
// Architecture: {obs_dim} -> {hidden} -> {hidden} -> {act_dim}, tanh
// Deterministic deployment of a SquashedDiagGaussian PPO policy.
// This file is trained by SR-Support; it is not copied from any other project.
#pragma once
#include <math.h>

#define POLICY_READY 1
#define POLICY_OBS_DIM {obs_dim}
#define POLICY_ACT_DIM {act_dim}
#define POLICY_HIDDEN {hidden}

{fmt_array("POLICY_W1", w1)}
{fmt_array("POLICY_B1", b1)}
{fmt_array("POLICY_W2", w2)}
{fmt_array("POLICY_B2", b2)}
{fmt_array("POLICY_W3", w3)}
{fmt_array("POLICY_B3", b3)}

static inline void policyForward(const float *obs, float *act) {{
  float h1[POLICY_HIDDEN];
  float h2[POLICY_HIDDEN];

  for (int o = 0; o < POLICY_HIDDEN; ++o) {{
    float s = POLICY_B1[o];
    for (int i = 0; i < POLICY_OBS_DIM; ++i) {{
      s += POLICY_W1[o * POLICY_OBS_DIM + i] * obs[i];
    }}
    h1[o] = tanhf(s);
  }}

  for (int o = 0; o < POLICY_HIDDEN; ++o) {{
    float s = POLICY_B2[o];
    for (int i = 0; i < POLICY_HIDDEN; ++i) {{
      s += POLICY_W2[o * POLICY_HIDDEN + i] * h1[i];
    }}
    h2[o] = tanhf(s);
  }}

  for (int o = 0; o < POLICY_ACT_DIM; ++o) {{
    float s = POLICY_B3[o];
    for (int i = 0; i < POLICY_HIDDEN; ++i) {{
      s += POLICY_W3[o * POLICY_HIDDEN + i] * h2[i];
    }}
    act[o] = tanhf(s);
  }}
}}
"""

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header, encoding="utf-8")
    print(f"Wrote {out} ({out.stat().st_size} bytes)")
    print("Set USE_RL_POLICY 1 in firmware/sr_support_2dof/config.h, then rebuild.")


if __name__ == "__main__":
    main()
